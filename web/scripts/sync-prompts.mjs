// Copies the versioned system prompts from the Python agent into the web app (the serverless agent can't read
// ../agent at runtime on Vercel). Run after editing agent/src/smiledesk/agent/prompts/*.md: npm run sync-prompts
// A unit test fails if this file is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, "../../agent/src/smiledesk/agent/prompts");
const out = path.resolve(here, "../lib/agent/prompts.generated.ts");
const prompts = Object.fromEntries(
  readdirSync(dir)
    .filter((f) => /^v\d+\.md$/.test(f))
    .sort()
    .map((f) => [f.replace(".md", ""), readFileSync(path.join(dir, f), "utf8")]),
);
writeFileSync(
  out,
  "// Generated by scripts/sync-prompts.mjs from agent/src/smiledesk/agent/prompts/*.md. Do not edit.\n" +
    `export const PROMPTS: Record<string, string> = ${JSON.stringify(prompts, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(prompts).join(", ")} → ${path.relative(process.cwd(), out)}`);
